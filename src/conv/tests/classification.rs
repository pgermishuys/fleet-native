#[test]
fn every_name_in_the_table_is_classified_as_the_client_does_today() {
    let rich = json!({
        "filePath": "src/widgets/panel.ts", "command": "dotnet test", "pattern": "*.ts", "url": "https://example.test/docs",
        "query": "reconnect backoff", "name": "fleet-run", "agent": "explore", "description": "Check the panel",
        "code": "await page.open()\nsecond line", "questions": [{"question": "Which folder?", "header": "Folder"}],
        "title": "Panel", "content": "one\ntwo",
    });
    for row in TODAY {
        let tool = get_tool(row.name);
        assert_eq!(tool.label(&serde_json::Value::Null), row.label_none, "{:?} label without input", row.name);
        assert_eq!(tool.label(&rich), row.label_rich, "{:?} label", row.name);
        assert_eq!(tool.icon, row.icon, "{:?} icon", row.name);
        assert_eq!(tool.heading, row.heading, "{:?} heading", row.name);
        assert_eq!(tool.category == Category::Subagent, row.subagent, "{:?} subagent", row.name);
        assert_eq!(tool.pattern_label, row.pattern, "{:?} pattern", row.name);
        assert_eq!(tool.titled_from_answer, row.titled, "{:?} titled from answer", row.name);
    }
}
